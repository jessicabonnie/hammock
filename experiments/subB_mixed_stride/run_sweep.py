#!/usr/bin/env python3
"""Sweep subB across the three --subB-method modes for hammock-cpp Mode B.

Iterates (size_class × method × subB × replicate), runs hammock-cpp Mode B on
the 6 BEDs of each size class (all 15 pairs), captures wall time, CPU time,
and max RSS via /usr/bin/time, and parses per-pair Jaccards from the CSV
output.

Methods compared: hash-threshold, mixed-stride, single-hash (the renamed
fast-subsample). subB=1.0 in any method = the "no subsample" baseline.

Writes a long-form CSV to results/. Each row is one (method, size_class,
subB, rep, file_a, file_b). Timing fields are attached identically to every
pair within a run.
"""

import argparse
import csv
import glob
import os
import re
import subprocess
import sys
import tempfile
import time
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent.parent
sys.path.insert(0, str(SCRIPT_DIR.parent / "bedtools_benchmark"))
from benchmark_cpp_vs_bedtools import (  # noqa: E402
    check_binary_version,
    find_hammock_cpp,
    get_system_info,
    run_with_time,
    SKETCH_RE,
    PAIR_RE,
    PAIRONLY_RE,
    WRITE_RE,
)

SUBB_VALUES = [1.0, 0.5, 0.25, 0.1, 0.05, 0.01]
SIZE_CLASSES = ["10k", "100k", "1M"]
METHODS = ["hash-threshold", "mixed-stride", "single-hash"]
CORPORA = ["synthetic", "maurano"]
FILES_PER_CLASS = 6
DEFAULT_REPS = 5
DEFAULT_PRECISION = 18
DEFAULT_THREADS = 8

DATA_DIR = SCRIPT_DIR / "data"
RESULTS_DIR = SCRIPT_DIR / "results"

ROW_COLS = [
    "corpus", "method", "size_class", "num_intervals", "subB", "rep", "run_id",
    "file_a", "file_b", "jaccard",
    # Populated only by the --metrics arm; empty in the register-equality shape.
    "jaccard_ie", "containment_AB", "containment_BA",
    "wall_time", "cpu_time", "max_rss_mb",
    # comparison_time keeps its historical meaning (pair loop + serial write);
    # pair_time/write_time decompose it.
    "sketch_creation_time", "comparison_time", "pair_time", "write_time",
    "precision", "threads",
    # Which output shape was timed. False = the cheap --register-equality arm
    # (renamed from --no-metrics; docs/seed-metrics-column-restructure.md)
    # every published Panel B number comes from; True = this script's own
    # --metrics flag, the IE-capture arm. The two are not timing-comparable,
    # so this must be readable off the row rather than inferred from the
    # filename.
    #
    # Part 9, retargeted 2026-08-11 (docs/seed-metrics-column-restructure.md):
    # the True/IE-capture arm used to pass hammock-cpp's own --metrics (the
    # 8-column full block, which also carries jaccard_ie/containment_AB/BA)
    # to get at jaccard_similarity_ie. Confirmed by re-reading
    # summarize_synthetic_ie.py -- the one live consumer of this arm's CSV --
    # that it reads neither jaccard_ie nor containment_AB/BA (only
    # wall_time/threads/subB/method/size_class/run_id/file_a/file_b), so it
    # now uses hammock-cpp's bare default (no flag), which gives
    # jaccard_similarity_ie alone at lower cost. See run_one() below.
    "metrics",
]

SIZE_TO_N = {"10k": 10_000, "100k": 100_000, "1M": 1_000_000}


def bed_paths_for(size_class: str) -> List[Path]:
    """Synthetic corpus: 6 BEDs per size class generated by generate_data.py."""
    return [DATA_DIR / f"bed_{size_class}_{i}.bed" for i in range(FILES_PER_CLASS)]


def bed_paths_for_maurano() -> List[Path]:
    """Maurano fetal-tissue DHS corpus: 20 BEDs symlinked by prepare_maurano.sh."""
    paths = sorted((DATA_DIR / "maurano").glob("*.bed"))
    if not paths:
        raise FileNotFoundError(
            f"no BEDs in {DATA_DIR / 'maurano'}; run prepare_maurano.sh first"
        )
    return paths


def groups_for_corpus(corpus: str, size_classes: List[str]):
    """Return [(size_class_label, num_intervals_hint, [bed paths]), ...]."""
    if corpus == "synthetic":
        return [(sc, SIZE_TO_N[sc], bed_paths_for(sc)) for sc in size_classes]
    if corpus == "maurano":
        beds = bed_paths_for_maurano()
        # Approx interval count from file sizes (each line ~30 bytes); only used
        # as a coarse num_intervals hint in the output CSV.
        avg_bytes = sum(p.stat().st_size for p in beds) / len(beds)
        return [("maurano", int(avg_bytes / 30), beds)]
    raise ValueError(f"unknown corpus: {corpus}")


def parse_hammock_csv(path: str) -> List[Dict[str, Any]]:
    """Hammock-cpp Mode B output, TAB-separated. Header depends on which of the
    three v0.8.0 output shapes was requested (docs/seed-metrics-column-
    restructure.md): register-equality has jaccard_similarity; full has both
    jaccard_similarity and jaccard_similarity_ie; bare default (used by this
    script's own --metrics/IE-capture arm since the 2026-08-11 retarget) has
    only jaccard_similarity_ie and no jaccard_similarity column at all -- so
    the "jaccard" field below must fall back to it, or every row from that
    arm would silently fail the `j is None` check and be dropped.
    """
    rows: List[Dict[str, Any]] = []
    with open(path) as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        for r in reader:
            j = (r.get("jaccard_similarity") or r.get("jaccard")
                 or r.get("jaccard_similarity_ie"))
            if j is None:
                continue
            # Capturing the IE column is the entire point of this script's own
            # --metrics arm. Absent (register-equality shape) these stay None
            # and reach the CSV empty.
            j_ie = r.get("jaccard_similarity_ie")
            c_ab = r.get("containment_AB")
            c_ba = r.get("containment_BA")
            rows.append({
                "file_a": os.path.basename(r.get("query") or r.get("file_a") or ""),
                "file_b": os.path.basename(r.get("reference") or r.get("file_b") or ""),
                "jaccard": float(j),
                "jaccard_ie": float(j_ie) if j_ie not in (None, "") else None,
                "containment_AB": float(c_ab) if c_ab not in (None, "") else None,
                "containment_BA": float(c_ba) if c_ba not in (None, "") else None,
            })
    return rows


def run_one(
    binary: str,
    method: str,
    beds: List[Path],
    subB: float,
    precision: int,
    threads: int,
    verbose: bool = False,
    metrics: bool = False,
) -> Dict[str, Any]:
    """Run hammock-cpp Mode B on the given BEDs; return timing + per-pair rows."""
    for p in beds:
        if not p.exists():
            raise FileNotFoundError(f"missing input: {p}")

    with tempfile.NamedTemporaryFile(mode="w", suffix=".txt", delete=False) as fh:
        listfile = fh.name
        for p in beds:
            fh.write(str(p) + "\n")

    with tempfile.NamedTemporaryFile(mode="w", suffix=".out", delete=False) as fh:
        out_prefix = fh.name

    try:
        cmd = [
            binary, listfile, listfile,
            "--mode", "B",
            "--subB", str(subB),
            "--subB-method", method,
            "-p", str(precision),
            "-t", str(threads),
            "-o", out_prefix,
            "--verbose",
        ]
        # Explicit in both directions: the shape of a timed pass must never be
        # implicit, since these wall times feed a published figure. This
        # script's own --metrics flag (`metrics` param) is the arm that
        # emits jaccard_similarity_ie, i.e. the column CLAUDE.md tells
        # readers to use; it is opt-in here because the existing Panel B
        # numbers are all --register-equality (renamed from --no-metrics;
        # docs/seed-metrics-column-restructure.md) and the two are not
        # comparable to each other.
        #
        # Retargeted 2026-08-11 (Part 9, docs/seed-metrics-column-
        # restructure.md): this used to pass hammock-cpp's own --metrics
        # (the 8-column full block) to get at jaccard_similarity_ie. The
        # bare default (no flag) gives that column alone since v0.8.0, at
        # lower cost, and the sole live consumer of this arm's output
        # (summarize_synthetic_ie.py) reads neither containment_AB/BA nor
        # jaccard_ie -- see the ROW_COLS comment above. So when `metrics` is
        # True, pass nothing; the shape-selecting flag is only needed for
        # the register-equality arm.
        if not metrics:
            cmd.append("--register-equality")
        if verbose:
            print("  +", " ".join(cmd), file=sys.stderr)
        r = run_with_time(cmd)

        sketch_s: Optional[float] = None
        pair_s: Optional[float] = None
        pair_only_s: Optional[float] = None
        write_s: Optional[float] = None
        for line in r["stderr"].splitlines():
            m = SKETCH_RE.match(line)
            if m:
                sketch_s = int(m.group(1)) / 1e6
                continue
            m = PAIR_RE.match(line)
            if m:
                pair_s = int(m.group(1)) / 1e6
                continue
            m = PAIRONLY_RE.match(line)
            if m:
                pair_only_s = int(m.group(1)) / 1e6
                continue
            m = WRITE_RE.match(line)
            if m:
                write_s = int(m.group(1)) / 1e6
        # Loud, not blank: an unparsed timing would otherwise reach the CSV as
        # an empty cell indistinguishable from "not measured". Most likely cause
        # is a pre-0.7.0 binary still reporting milliseconds.
        if sketch_s is None or pair_s is None:
            raise RuntimeError(
                "could not parse hammock-cpp timing lines (need >= 0.7.0, which "
                f"reports microseconds). stderr was:\n{r['stderr']}")
        r["sketch_creation_time"] = sketch_s
        r["comparison_time"] = pair_s
        r["pair_time"] = pair_only_s
        r["write_time"] = write_s

        csvs = [f for f in glob.glob(out_prefix + "*") if f.endswith(".csv")]
        if not csvs:
            raise RuntimeError(f"no CSV produced; stderr=\n{r['stderr'][-500:]}")
        pairs = parse_hammock_csv(csvs[0])
        # keep only unordered self-pairs once: file_a < file_b (lex), drop equal
        seen = set()
        kept = []
        for row in pairs:
            a, b = row["file_a"], row["file_b"]
            if a == b:
                continue
            key = tuple(sorted((a, b)))
            if key in seen:
                continue
            seen.add(key)
            # Carry the whole row through rather than rebuilding it from three
            # named keys: the metrics columns were silently dropped here even
            # after parse_hammock_csv started reading them, which is how the
            # --metrics arm came to write a file containing no metrics.
            kept.append({**row, "file_a": key[0], "file_b": key[1]})

        r["pairs"] = kept
        return r
    finally:
        os.unlink(listfile)
        for f in glob.glob(out_prefix + "*"):
            try:
                os.remove(f)
            except OSError:
                pass


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", default="synthetic", choices=CORPORA,
                        help="BED corpus: synthetic (default) or maurano")
    parser.add_argument("--size-classes", nargs="+", default=SIZE_CLASSES,
                        choices=SIZE_CLASSES,
                        help="Synthetic-only: subset of size classes to run")
    parser.add_argument("--methods", nargs="+", default=METHODS,
                        choices=METHODS, help="--subB-method values to sweep")
    parser.add_argument("--subB-values", nargs="+", type=float, default=SUBB_VALUES,
                        help="subB values to sweep")
    parser.add_argument("--reps", type=int, default=DEFAULT_REPS,
                        help="Replicate runs per (method, size_class, subB) cell")
    parser.add_argument("--precision", "-p", type=int, default=DEFAULT_PRECISION,
                        help="HLL precision")
    parser.add_argument("--threads", "-t", type=int, default=DEFAULT_THREADS,
                        help="Threads passed to hammock-cpp")
    parser.add_argument("--binary", default=None, help="Override hammock-cpp path")
    parser.add_argument("--output", default=None,
                        help="Output CSV path (default: results/sweep_<timestamp>.csv)")
    parser.add_argument("--verbose", action="store_true", help="Print every command")
    parser.add_argument("--metrics", action="store_true",
                        help="Time the jaccard_similarity_ie-capture arm (hammock-cpp's "
                             "bare default shape, no flag; retargeted 2026-08-11, was "
                             "hammock-cpp's --metrics full block -- see "
                             "docs/seed-metrics-column-restructure.md Part 9) instead of "
                             "the cheap --register-equality arm. Writes to "
                             "sweep_<corpus>_ie_<stamp>.csv so it cannot be mistaken for, "
                             "or auto-adopted as, the headline sweep. Not "
                             "timing-comparable to a run without it.")
    parser.add_argument("--smoke", action="store_true",
                        help="Smoke test: one rep at one subB on smallest class")
    args = parser.parse_args()

    if args.smoke:
        args.size_classes = ["10k"]
        args.methods = METHODS
        args.subB_values = [0.1]
        args.reps = 1

    binary = args.binary or find_hammock_cpp()
    check_binary_version(binary)
    groups = groups_for_corpus(args.corpus, args.size_classes)
    print(f"hammock-cpp: {binary}")
    print(f"corpus:       {args.corpus}")
    print(f"groups:       {[(g[0], len(g[2])) for g in groups]}")
    print(f"methods:      {args.methods}")
    print(f"subB values:  {args.subB_values}")
    print(f"reps:         {args.reps}")
    print(f"precision:    {args.precision}")
    print(f"threads:      {args.threads}")
    print(f"output shape: {'bare default (ie, jaccard_similarity_ie only)' if args.metrics else 'register-equality (--register-equality)'}")
    print(f"system:       {get_system_info()}")
    print()

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    if args.output:
        out_path = Path(args.output)
    else:
        # The `ie_` infix is load-bearing, not cosmetic: analyze.R,
        # headline_figures.R and pareto_variants.R pick_latest on
        # ^sweep_<corpus>_[0-9] and would otherwise adopt this file as the
        # newest sweep, silently republishing metrics-arm wall times as the
        # headline subB numbers. A non-digit after the corpus fails that glob.
        infix = "ie_" if args.metrics else ""
        out_path = RESULTS_DIR / f"sweep_{args.corpus}_{infix}{stamp}.csv"

    with open(out_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=ROW_COLS)
        w.writeheader()

        run_id = 0
        total = (len(groups) * len(args.methods)
                 * len(args.subB_values) * args.reps)
        t_start = time.time()

        for size_class, n_int, beds in groups:
            for method in args.methods:
                for subB in args.subB_values:
                    for rep in range(args.reps):
                        run_id += 1
                        elapsed = time.time() - t_start
                        print(f"[{run_id:>3}/{total}] corpus={args.corpus} size={size_class} method={method} subB={subB} rep={rep+1}/{args.reps}  (elapsed {elapsed:.1f}s)",
                              flush=True)
                        r = run_one(binary, method, beds, subB,
                                    args.precision, args.threads,
                                    verbose=args.verbose, metrics=args.metrics)
                        for pair in r["pairs"]:
                            w.writerow({
                                "corpus": args.corpus,
                                "method": method,
                                "size_class": size_class,
                                "num_intervals": n_int,
                                "subB": subB,
                                "rep": rep,
                                "run_id": run_id,
                                "file_a": pair["file_a"],
                                "file_b": pair["file_b"],
                                "jaccard": pair["jaccard"],
                                "jaccard_ie": pair.get("jaccard_ie"),
                                "containment_AB": pair.get("containment_AB"),
                                "containment_BA": pair.get("containment_BA"),
                                "wall_time": r["wall_time"],
                                "cpu_time": r["cpu_time"],
                                "max_rss_mb": r["max_rss_mb"],
                                "sketch_creation_time": r["sketch_creation_time"],
                                "comparison_time": r["comparison_time"],
                                "pair_time": r["pair_time"],
                                "write_time": r["write_time"],
                                "precision": args.precision,
                                "threads": args.threads,
                                "metrics": args.metrics,
                            })
                        fh.flush()
                        print(f"      wall={r['wall_time']:.2f}s sketch={r['sketch_creation_time']}s pair={r['comparison_time']}s pairs={len(r['pairs'])}",
                              flush=True)

    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
