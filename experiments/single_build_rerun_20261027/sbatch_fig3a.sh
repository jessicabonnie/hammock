#!/bin/bash
#SBATCH --job-name=sbr_fig3a
#SBATCH --partition=parallel
#SBATCH --account=blangme2
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --exclusive
#SBATCH --mem=0
#SBATCH --time=03:00:00
#SBATCH --output=/home/jbonnie1/interval_sketch/hammock_claude/experiments/single_build_rerun_20261027/logs/fig3a_%j.out
#SBATCH --error=/home/jbonnie1/interval_sketch/hammock_claude/experiments/single_build_rerun_20261027/logs/fig3a_%j.err

# Figure 3A (collection-size scaling) with the single 0.12.0 build.
# Reproduces experiments/bedtools_benchmark/sbatch_fig3_panelA_v2.sh, archived
# 0.7.0 run job 29671317 (c529) -> docs/data/cpp_vs_bedtools_t16_p18.csv:
#   synthetic, 10,000 intervals/file, N = 2..512, p = 18, 16 threads/processes,
#   arms bedtools + hammock --register-equality + hammock IE (--metrics-arm),
#   arm order rotated by replicate, corpus seed 20260810 (identical inputs,
#   regenerated by the same seeded generator), one exclusive 48-core 6248R node,
#   two passes: N <= 32 at 20 replicates, N >= 64 at 3 replicates.
# Harness: copies in harness/ (paths repointed into this directory only).
# Known difference from job 29671317: the IE arm now runs the bare default
# (jaccard_similarity_ie only) instead of --metrics (full block); harness
# change of 2026-08-11 (Part 9), same as the confirming rerun job 29769994.

set -euo pipefail
source /home/jbonnie1/interval_sketch/hammock_claude/experiments/single_build_rerun_20261027/common.sh
require_cpu 6248R
require_sha "$SINGLE_BINARY" "$SINGLE_SHA"
cd "$EXP"

ml bedtools/2.30.0
ml parallel
export HAMMOCK_CPP_BIN=$SINGLE_BINARY

OUT=$EXP/results/fig3a
FIG=$EXP/figures/fig3a
mkdir -p "$OUT" "$FIG"
META=$OUT/metadata_${SLURM_JOB_ID}.txt
write_metadata "$META" "$SINGLE_BINARY"

echo; echo "================ low N, n=20 ================"
"$PY_HAMMOCK" harness/benchmark_cpp_vs_bedtools.py \
    --binary "$SINGLE_BINARY" \
    --threads 16 --precision 18 --num-intervals 10000 \
    --num-files 2,4,8,16,32 \
    --metrics-arm \
    --runs 20 \
    --corpus-seed 20260810 \
    --output-dir "$OUT" --figures-dir "$FIG"
echo "low_N_pass_end: $(date -Is)" | tee -a "$META"

echo; echo "================ high N, n=3 ================"
"$PY_HAMMOCK" harness/benchmark_cpp_vs_bedtools.py \
    --binary "$SINGLE_BINARY" \
    --threads 16 --precision 18 --num-intervals 10000 \
    --num-files 64,128,256,512 \
    --metrics-arm \
    --runs 3 \
    --corpus-seed 20260810 \
    --output-dir "$OUT" --figures-dir "$FIG"

finish_metadata "$META"
